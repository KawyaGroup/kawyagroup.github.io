// Shared, XSS-safe DOM helpers. Text always goes in as text nodes, never as HTML.
export function h(tag, attrs, ...kids) {
  const el = document.createElement(tag);
  if (attrs) for (const [k, v] of Object.entries(attrs)) {
    if (v == null || v === false) continue;
    if (k === 'class') el.className = v;
    else if (k === 'text') el.textContent = v;
    else if (k.startsWith('on') && typeof v === 'function') el.addEventListener(k.slice(2), v);
    else if (k === 'style' && typeof v === 'object') Object.assign(el.style, v);
    else if (k === 'href') { if (/^(#|https:\/\/|tel:|mailto:)/.test(v)) el.setAttribute('href', v); }
    else if (k === 'src') { if (/^(data:image\/|assets\/|https:\/\/www\.google\.com\/maps)/.test(v)) el.setAttribute('src', v); }
    else el.setAttribute(k, v === true ? '' : v);
  }
  for (const c of kids.flat(Infinity)) if (c != null && c !== false) el.append(c instanceof Node ? c : document.createTextNode(String(c)));
  return el;
}

